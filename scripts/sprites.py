# Writes the island's pixel mascots: the five members as tiny SD chibis
# (pixel-art/holo-tiny/build.py, 24 x 26 on a 32 x 32 canvas), every
# animation frame, facing right and (-l) left, into app/assets/sprites/, and
# app/ui/sprites.slint to pick them. Our own pixel art (pixel-art-studio).
#   python scripts/sprites.py            (add --preview <png> for a contact sheet)
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "pixel-art", "holo-tiny"))
from PIL import Image  # noqa: E402
import build as holo  # noqa: E402

ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "app", "assets", "sprites")
N = 32


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(".png"):
            os.remove(os.path.join(OUT, f))
    lines = [
        "// Generated by scripts/sprites.py: do not edit. The mascot frames of",
        "// every theme (32 x 32: show them at whole multiples), facing right",
        "// and (-l) left.",
        "",
        "export global Sprites {",
    ]
    cell = N + 2
    sheet = Image.new("RGBA", (len(holo.FRAMES) * 2 * cell, len(holo.MEMBERS) * cell), (11, 20, 36, 255))
    # One small function per theme and side: a single chain of ifs this long
    # overflows the Slint compiler's stack.
    for mi, member in enumerate(holo.MEMBERS):
        for side in ("", "-l"):
            lines.append(f"    pure function {member}{'_l' if side else '_r'}(frame: string) -> image {{")
            for fi, frame in enumerate(holo.FRAMES):
                img = holo.framed(member, frame)
                if side:
                    img = img.transpose(Image.FLIP_LEFT_RIGHT)
                img.save(os.path.join(OUT, f"{member}-{frame}{side}.png"))
                sheet.paste(img, ((fi * 2 + (1 if side else 0)) * cell + 1, mi * cell + 1), img)
                lines.append(f'        if (frame == "{frame}") {{ return @image-url("../assets/sprites/{member}-{frame}{side}.png"); }}')
            lines += [f'        return @image-url("../assets/sprites/{member}-idle{side}.png");', "    }"]
    lines.append("    pure public function pick(theme: string, frame: string, left: bool) -> image {")
    for member in holo.MEMBERS:
        lines.append(f'        if (theme == "{member}") {{ return left ? self.{member}_l(frame) : self.{member}_r(frame); }}')
    lines += ["        return left ? self.fubuki_l(frame) : self.fubuki_r(frame);", "    }", "}"]
    with open(os.path.join(ROOT, "app", "ui", "sprites.slint"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    if "--preview" in sys.argv:
        sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(sys.argv[sys.argv.index("--preview") + 1])
    print(f"{len(holo.MEMBERS) * len(holo.FRAMES) * 2} frames written to {os.path.abspath(OUT)}")


if __name__ == "__main__":
    main()
